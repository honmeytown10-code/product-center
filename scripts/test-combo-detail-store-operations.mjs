import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
import assert from 'node:assert/strict';
const module = { exports: {} };
vm.runInNewContext(ts.transpileModule(fs.readFileSync('components/web/comboDetailStoreOperations.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, { exports: module.exports });
const { applyDetailShelfChange, detailChannels } = module.exports;
const record = { id: 'r', baseProductId: 'combo', storeId: 's', storeName: '测试店', channels: ['mini_program_dine_in', 'pos'], status: 'on_shelf', stockCount: 12, formData: { s_price: '168' } };
const request = { productId: 'combo', channelId: 'mini_dine', targets: [{ id: 'r', expectedStatus: 'on_shelf' }], status: 'off_shelf' };
const changed = applyDetailShelfChange([record], request);
assert.equal(changed.succeededIds.length, 1);
assert.equal(record.status, 'on_shelf');
assert.equal(changed.records.find(row => row.channels.includes('pos')).status, 'on_shelf');
const dine = changed.records.find(row => row.channels.includes('mini_program_dine_in'));
assert.equal(dine.status, 'off_shelf'); assert.equal(dine.stockCount, 12); assert.equal(dine.formData.s_price, '168');
const restored = applyDetailShelfChange(changed.records, { ...request, targets: [{ id: dine.id, expectedStatus: 'off_shelf' }], status: 'on_shelf' });
assert.equal(restored.records.find(row => row.id === dine.id).status, 'on_shelf');
const partial = applyDetailShelfChange([record], { ...request, targets: [...request.targets, { id: 'removed', expectedStatus: 'on_shelf' }] });
assert.equal(partial.succeededIds.length, 1); assert.equal(partial.failures.length, 1);
const wrongProduct = applyDetailShelfChange([record], { ...request, productId: 'other' });
assert.equal(wrongProduct.failures.length, 1); assert.equal(wrongProduct.records[0].status, 'on_shelf');
const off = { ...record, status: 'off_shelf' };
const idempotent = applyDetailShelfChange([off], request);
assert.equal(idempotent.records.length, 1); assert.equal(idempotent.succeededIds.length, 1);
const channels = detailChannels([record], 'combo', ['mini_program_delivery', 'mini_dine']);
assert.equal(channels.join(','), 'mini_dine,mini_take,pos'); assert(!channels.includes('all'));
console.log('Passed: channel isolation, canonical aliases, price/stock preservation, restoration, partial failure, object boundary and idempotency.');
