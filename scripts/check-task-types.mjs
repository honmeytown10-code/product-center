import ts from 'typescript';
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
const root = process.cwd();
const tracked = new Set(execFileSync('git', ['ls-files'], { encoding: 'utf8' }).trim().split('\n'));
const changed = execFileSync('git', ['diff', '--name-only'], { encoding: 'utf8' }).trim().split('\n').filter(file => /\.tsx?$/.test(file));
const originals = new Map(changed.map(file => [file, execFileSync('git', ['show', `HEAD:${file}`], { encoding: 'utf8', maxBuffer: 8e6 })]));
const config = ts.readConfigFile('tsconfig.json', ts.sys.readFile);
const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, root);
const host = ts.createCompilerHost(parsed.options);
const read = host.readFile;
host.readFile = filename => originals.get(path.relative(root, filename).replaceAll('\\', '/')) ?? read(filename);
const baseline = ts.createProgram(parsed.fileNames.filter(file => tracked.has(path.relative(root, file).replaceAll('\\', '/'))), parsed.options, host);
const base = ts.getPreEmitDiagnostics(baseline);
const current = ts.getPreEmitDiagnostics(ts.createProgram(parsed.fileNames, parsed.options));
const signature = diagnostic => `${diagnostic.file ? path.relative(root, diagnostic.file.fileName) : ''}:${diagnostic.code}:${ts.flattenDiagnosticMessageText(diagnostic.messageText, '\n')}`;
const counts = new Map();
for (const item of base) counts.set(signature(item), (counts.get(signature(item)) || 0) + 1);
const introduced = current.filter(item => { const key = signature(item), count = counts.get(key) || 0; if (count) { counts.set(key, count - 1); return false; } return true; });
const output = { baselineDiagnostics: base.length, currentDiagnostics: current.length, introduced: introduced.map(item => signature(item)) };
fs.writeFileSync('task-review/types-baseline-comparison.json', JSON.stringify(output, null, 2));
console.log(JSON.stringify(output));
if (introduced.length) process.exitCode = 1;
