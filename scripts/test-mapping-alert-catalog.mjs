import assert from 'node:assert/strict';
import { lookupLibrarySku, lookupLibraryTradeMark, DEMO_LIBRARY_PRODUCTS } from '../components/mobile/mappingAlertCatalog.ts';
const result = lookupLibrarySku('623802011');
assert.equal(result.status, 'found');
assert.equal(result.product.name, '生椰丝绒拿铁');
assert.equal(result.sku.spec, '大杯 · 冰');
assert.equal(lookupLibrarySku('623899999').status, 'missing');
assert.equal(lookupLibrarySku('生椰丝绒拿铁').status, 'missing');
assert.equal(lookupLibrarySku('0623802011').status, 'missing');
assert.equal(lookupLibrarySku('').status, 'missing');
assert.equal(lookupLibrarySku('623802111').status, 'found');
assert.equal(lookupLibrarySku('623802111').product.ready, false);
assert.equal(lookupLibrarySku('623802011', [...DEMO_LIBRARY_PRODUCTS, { ...DEMO_LIBRARY_PRODUCTS[0], id: 'duplicate' }]).status, 'ambiguous');
const tradeMark = lookupLibraryTradeMark('COFFEE-SILKY-ICE');
assert.equal(tradeMark.status, 'found');
assert.equal(tradeMark.sku.id, '623802011');
assert.equal(lookupLibraryTradeMark('623802011').status, 'missing');
assert.equal(lookupLibrarySku('COFFEE-SILKY-ICE').status, 'missing');
assert.equal(lookupLibraryTradeMark('').status, 'missing');
assert.equal(lookupLibraryTradeMark('   ').status, 'missing');
assert.equal(lookupLibraryTradeMark('COFFEE-UNKNOWN-ICE').status, 'missing');
assert.equal(lookupLibraryTradeMark('COFFEE-SILKY-ICE', [...DEMO_LIBRARY_PRODUCTS, { ...DEMO_LIBRARY_PRODUCTS[0], id: 'duplicate' }]).status, 'ambiguous');
console.log('Catalog lookup: 18 assertions passed');
